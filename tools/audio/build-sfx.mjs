// Builds public/audio/sfx.{ogg,m4a} (one mono sprite) + src/audio/sfxSprite.ts from Kenney CC0 packs
// and the rendered stingers. Usage: node tools/audio/build-sfx.mjs <kenneyDir> <renderDir>
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const [kenney = '../sprint/audio-src', rendered = '../sprint/audio-build'] = process.argv.slice(2);
const K = (pack, file) => join(kenney, pack, 'Audio', file);
// [sprite key, source file, gain dB]
const LIST = [
  ['ui_hover', K('ui-audio', 'rollover2.ogg'), -6],
  ['ui_click', K('interface-sounds', 'click_002.ogg'), -2],
  ['ui_confirm', K('interface-sounds', 'confirmation_002.ogg'), -3],
  ['ui_back', K('interface-sounds', 'back_002.ogg'), -3],
  ['ui_toggle', K('interface-sounds', 'switch_003.ogg'), -3],
  ['ui_error', K('interface-sounds', 'error_006.ogg'), -4],
  ['imp_light_0', K('impact-sounds', 'impactPlate_light_000.ogg'), 0],
  ['imp_light_1', K('impact-sounds', 'impactPlate_light_001.ogg'), 0],
  ['imp_light_2', K('impact-sounds', 'impactPlate_light_002.ogg'), 0],
  ['imp_med_0', K('impact-sounds', 'impactWood_medium_000.ogg'), 0],
  ['imp_med_1', K('impact-sounds', 'impactWood_medium_001.ogg'), 0],
  ['imp_med_2', K('impact-sounds', 'impactWood_medium_002.ogg'), 0],
  ['imp_heavy_0', K('impact-sounds', 'impactSoft_heavy_000.ogg'), 0],
  ['imp_heavy_1', K('impact-sounds', 'impactSoft_heavy_001.ogg'), 0],
  ['imp_heavy_2', K('impact-sounds', 'impactSoft_heavy_002.ogg'), 0],
  ['grab', K('interface-sounds', 'pluck_001.ogg'), -2],
  ['drop', K('interface-sounds', 'drop_002.ogg'), -2],
  ['hack_tick', K('interface-sounds', 'tick_002.ogg'), -4],
  ['hack_ok', K('interface-sounds', 'confirmation_004.ogg'), -2],
  ['hack_fail', K('interface-sounds', 'error_004.ogg'), -3],
  ['glitch', K('interface-sounds', 'glitch_002.ogg'), -4],
  ['zap', K('digital-audio', 'zapTwoTone.ogg'), -6],
  ['vault_door', K('sci-fi-sounds', 'doorOpen_001.ogg'), -2],
  ['capture', K('sci-fi-sounds', 'forceField_001.ogg'), -4],
  ['sting_theft', join(rendered, 'sting-theft.wav'), -1],
  ['sting_win', join(rendered, 'sting-win.wav'), -1],
  ['sting_vault', join(rendered, 'sting-vault.wav'), -3],
];
const GAP = 0.08;
const SR = 44100;
const tmp = mkdtempSync(join(tmpdir(), 'sfx-'));
const map = {};
const parts = [];
let cursor = 0;
for (const [key, src, db] of LIST) {
  if (!existsSync(src)) throw new Error(`missing ${src}`);
  const raw = join(tmp, `${key}.raw`);
  // mono, 44.1k, trim leading/trailing silence, peak-normalise to -1 dBFS then apply gain
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', src, '-ac', '1', '-ar', String(SR), '-af',
    'silenceremove=start_periods=1:start_threshold=-55dB,areverse,silenceremove=start_periods=1:start_threshold=-60dB,afade=t=in:d=0.004,areverse',
    '-f', 'f32le', raw]);
  const buf = readFileSync(raw);
  const f = new Float32Array(buf.buffer, buf.byteOffset, buf.length / 4);
  let peak = 0; for (const v of f) peak = Math.max(peak, Math.abs(v));
  const g = (10 ** (-1 / 20) / (peak || 1)) * 10 ** (db / 20);
  const scaled = Float32Array.from(f, (v) => v * g);
  const dur = scaled.length / SR;
  map[key] = [+cursor.toFixed(4), +dur.toFixed(4)];
  parts.push(scaled, new Float32Array(Math.round(GAP * SR)));
  cursor += dur + Math.round(GAP * SR) / SR;
}
const total = parts.reduce((n, p) => n + p.length, 0);
const all = new Float32Array(total); let o = 0; for (const p of parts) { all.set(p, o); o += p.length; }
const rawAll = join(tmp, 'all.raw'); writeFileSync(rawAll, Buffer.from(all.buffer));
const inArgs = ['-v', 'error', '-y', '-f', 'f32le', '-ar', String(SR), '-ac', '1', '-i', rawAll];
execFileSync('ffmpeg', [...inArgs, '-c:a', 'libvorbis', '-q:a', '3', 'public/audio/sfx.ogg']);
execFileSync('ffmpeg', [...inArgs, '-c:a', 'aac', '-b:a', '80k', '-movflags', '+faststart', 'public/audio/sfx.m4a']);
const ts = `// Generated by tools/audio/build-sfx.mjs. Do not edit by hand.\n// [start s, duration s] inside public/audio/sfx.{ogg,m4a}\nexport const SFX_SPRITE = ${JSON.stringify(map, null, 1).replace(/\n\s*(\d)/g, ' $1').replace(/\n\s*\]/g, ']')} as const;\nexport type SpriteKey = keyof typeof SFX_SPRITE;\n`;
writeFileSync('src/audio/sfxSprite.ts', ts);
console.log(`sprite ${cursor.toFixed(2)} s, ${LIST.length} sounds`);
